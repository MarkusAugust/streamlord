/**
 * The DOM events an element can be listened to for, read from TypeScript's lib.dom.d.ts: the keys
 * of GlobalEventHandlersEventMap, each with the MDN link its on<name> handler carries. Both
 * editors offer them after `data-on:`; generate.mjs writes them to catalog/dom-events.json, and a
 * test holds that file to the TypeScript this package pins.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

/** lib.dom.d.ts of the TypeScript in node_modules, and its version. */
export function pinnedLibDom() {
  const require = createRequire(import.meta.url);
  const pkg = require.resolve("typescript/package.json");
  return { version: JSON.parse(readFileSync(pkg, "utf8")).version, text: readFileSync(pkg.replace(/package\.json$/, "lib/lib.dom.d.ts"), "utf8") };
}

/** The interface named `name` in `text`, from its opening line to the closing brace at the start of a line. */
function body(text, name) {
  const start = text.indexOf(`\ninterface ${name} {`);
  if (start < 0) throw new Error(`lib.dom.d.ts has no interface ${name}`);
  return text.slice(start, text.indexOf("\n}", start));
}

/**
 * The prefixed events lib.dom.d.ts keys by their handler's lower-case name, with the name the
 * browser dispatches them under: the HTML standard's table of event handlers maps
 * onwebkitanimationend to webkitAnimationEnd (https://html.spec.whatwg.org/#event-handlers-on-elements,-document-objects,-and-window-objects).
 */
const DISPATCHED = {
  webkitanimationend: "webkitAnimationEnd",
  webkitanimationiteration: "webkitAnimationIteration",
  webkitanimationstart: "webkitAnimationStart",
  webkittransitionend: "webkitTransitionEnd",
};

/** The events of GlobalEventHandlersEventMap in its order, each with its MDN link or null and the interface its listener is handed. */
export function domEvents(text) {
  const entries = [...body(text, "GlobalEventHandlersEventMap").matchAll(/^\s+"([a-z]+)": (\w+);/gm)];
  const links = new Map(
    [...body(text, "GlobalEventHandlers").matchAll(/\[MDN Reference\]\((https:[^)]+)\)\s*\*\/\s*\n\s+on([a-z]+):/g)].map((m) => [m[2], m[1]]),
  );
  return entries.map(([, name, type]) => ({ name: DISPATCHED[name] ?? name, mdn: links.get(name) ?? null, interface: type }));
}

/**
 * The event interfaces those events are handed, CustomEvent among them for the events a page
 * dispatches itself, each with the one it extends and its own members, in the order lib.dom.d.ts
 * declares them: a member's name, whether it is a method, and its MDN link. A deprecated member and
 * a constant are left out.
 */
export function eventInterfaces(text, events) {
  const out = {};
  const add = (name) => {
    if (name in out) return;
    // CustomEvent<T = any> and ProgressEvent<T extends EventTarget = EventTarget> take a type parameter.
    const found = new RegExp(`\\ninterface ${name}(?:<[^>]*>)? (?:extends (\\w+) )?\\{`).exec(text);
    if (!found) throw new Error(`lib.dom.d.ts has no interface ${name}`);
    const start = found.index;
    const parent = found[1] ?? null;
    const members = [];
    for (const m of text.slice(start, text.indexOf("\n}", start)).matchAll(/\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*\n {4}(?:readonly )?([A-Za-z_]\w*)(\??)(\(|:)/g)) {
      const [, doc, member, , kind] = m;
      if (doc.includes("@deprecated") || /^[A-Z_]+$/.test(member) || members.some((x) => x.name === member)) continue;
      members.push({ name: member, method: kind === "(", mdn: /\[MDN Reference\]\((https:[^)]+)\)/.exec(doc)?.[1] ?? null });
    }
    out[name] = { extends: parent, members };
    if (parent) add(parent);
  };
  for (const e of events) add(e.interface);
  add("CustomEvent");
  return out;
}

/** catalog/dom-events.json as generate.mjs writes it. */
export function domEventsFile({ version, text }) {
  const file = {
    $comment: `The DOM events an element can be listened to for, offered after data-on: in both editors: GlobalEventHandlersEventMap of TypeScript ${version}'s lib.dom.d.ts, with the MDN links of its handlers and the interface each listener is handed, and in interfaces the members of those interfaces. Generated by editors/vscode/scripts/generate.mjs; do not edit. Not part of Datastar's surface, which datastar-1.0.5.json holds.`,
    events: domEvents(text),
  };
  file.interfaces = eventInterfaces(text, file.events);
  return JSON.stringify(file, null, 2) + "\n";
}
