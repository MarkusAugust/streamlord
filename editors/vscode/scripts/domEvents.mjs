/**
 * The DOM events an element can be listened to for, read from TypeScript's lib.dom.d.ts: the keys
 * of GlobalEventHandlersEventMap, each with the MDN link its on<name> handler carries. Both
 * editors offer them after `data-on:`; generate.mjs writes them to catalog/dom-events.json, and a
 * test holds that file to the TypeScript this package pins.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

/** lib.dom.d.ts of the TypeScript in node_modules, and its version. */
export function pinnedLibDom() {
  const require = createRequire(import.meta.url);
  const pkg = require.resolve("typescript/package.json");
  return { version: JSON.parse(readFileSync(pkg, "utf8")).version, text: readFileSync(pkg.replace(/package\.json$/, "lib/lib.dom.d.ts"), "utf8") };
}

/** The interface named `name` in `text`, from its opening line to the closing brace at the start of a line. */
function body(text, name) {
  const start = text.indexOf(`\ninterface ${name} {`);
  if (start < 0) throw new Error(`lib.dom.d.ts has no interface ${name}`);
  return text.slice(start, text.indexOf("\n}", start));
}

/** The events of GlobalEventHandlersEventMap in its order, each with its MDN link or null. */
export function domEvents(text) {
  const names = [...body(text, "GlobalEventHandlersEventMap").matchAll(/^\s+"([a-z]+)":/gm)].map((m) => m[1]);
  const links = new Map(
    [...body(text, "GlobalEventHandlers").matchAll(/\[MDN Reference\]\((https:[^)]+)\)\s*\*\/\s*\n\s+on([a-z]+):/g)].map((m) => [m[2], m[1]]),
  );
  return names.map((name) => ({ name, mdn: links.get(name) ?? null }));
}

/** catalog/dom-events.json as generate.mjs writes it. */
export function domEventsFile({ version, text }) {
  const file = {
    $comment: `The DOM events an element can be listened to for, offered after data-on: in both editors: GlobalEventHandlersEventMap of TypeScript ${version}'s lib.dom.d.ts, with the MDN links of its handlers. Generated by editors/vscode/scripts/generate.mjs; do not edit. Not part of Datastar's surface, which datastar-1.0.4.json holds.`,
    events: domEvents(text),
  };
  return JSON.stringify(file, null, 2) + "\n";
}
